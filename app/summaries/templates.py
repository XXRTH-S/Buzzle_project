def meeting_template(id: str, label: str, hint: str, focus: str,
                     sections: dict[str, list[str]], headline: str, summary: str) -> Template:
    section_schema = create_model(
        f"{id}_sections",
        __config__=ConfigDict(extra="forbid"),
        **{title: (list[str], ...) for title in sections},
    )
    schema = create_model(f"{id}_summary", headline=(str, ...), summary=(str, ...),
                          sections=(section_schema, ...))
    instruction = (
        f"สรุปในรูปแบบ {label} โดยเน้น {focus}\n"
        "headline: ชื่อเรื่องสั้น ๆ; summary: ภาพรวม 2–4 ประโยค; sections: แยกตามหัวข้อใน schema "
        "แต่ละหัวข้อเป็นรายการข้อความที่กระชับและใช้ต่อได้ เรียงตามความสำคัญ "
        "ถ้าไม่มีข้อมูลให้คืนรายการว่าง ห้ามแต่งชื่อ ผู้รับผิดชอบ กำหนดส่ง งบประมาณ มติ หรือผลลงคะแนน "
        "แยกข้อเสนอออกจากข้อสรุปที่ตกลงแล้วเสมอ\n"
        + "หัวข้อที่ต้องแยก: " + ", ".join(sections)
    )
    return Template(id, label, hint, instruction, schema, tuple(sections),
                    {"headline": headline, "summary": summary, "sections": sections})


